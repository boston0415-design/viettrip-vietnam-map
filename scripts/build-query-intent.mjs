// Compile the same pure intent rules for server and browser; no API/provider code.
import {readFile,writeFile} from 'node:fs/promises';
const source=await readFile(new URL('../functions/api/ask-map.js',import.meta.url),'utf8');
const pure=source.slice(0,source.indexOf('export async function readBody'))
  .replace(/const SYSTEM=`[\s\S]*?(?=const strings=)/,'')
  .replace(/^export /gm,'');
const output='// Generated by scripts/build-query-intent.mjs. Edit functions/api/ask-map.js.\n(()=>{\n'+pure+'\nwindow.AIQueryIntent={contextualIntent,recoveryIntent,exploratoryIntent};\n})();\n';
await writeFile(new URL('../assets/js/ai-query-intent.js',import.meta.url),output);
